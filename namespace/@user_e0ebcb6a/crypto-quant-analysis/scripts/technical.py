def build_parser() -> argparse.ArgumentParser:
    """Build CLI argument parser."""
    parser = argparse.ArgumentParser(
        description="Technical indicator calculator (Gate/OKX)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s --action rsi --symbol BTC
  %(prog)s --action macd --symbol ETH --timeframe 4h
  %(prog)s --action bollinger --symbol SOL
  %(prog)s --action all --symbol BTC --timeframe 1d
""",
    )
    parser.add_argument(
        "--action", type=str, required=True,
        choices=["rsi", "macd", "bollinger", "all"],
        help="Indicator to compute.",
    )
    parser.add_argument("--symbol", type=str, default="BTC",
                        help="Trading pair (default: BTC/USDT)")
    parser.add_argument("--timeframe", type=str, default="1d",
                        help="Candle interval (default: 1d)")
    parser.add_argument("--limit", type=int, default=200,
                        help="Number of candles (default: 200)")
    return parser


def main() -> None:
    """CLI entry point."""
    parser = build_parser()
    args = parser.parse_args()

    try:
        if args.action == "rsi":
            print(action_rsi(args.symbol, args.timeframe, args.limit))
        elif args.action == "macd":
            print(action_macd(args.symbol, args.timeframe))
        elif args.action == "bollinger":
            print(action_bollinger(args.symbol, args.timeframe))
        elif args.action == "all":
            print(action_all(args.symbol, args.timeframe, args.limit))
        else:
            parser.error(f"Unknown action: {args.action}")
    except (ValueError, RuntimeError) as e:
        logger.error("Execution failed: %s", e)
        sys.exit(1)


if __name__ == "__main__":
    main()
