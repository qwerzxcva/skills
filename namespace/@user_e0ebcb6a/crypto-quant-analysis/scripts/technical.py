def _attach_all_indicators(df: pd.DataFrame) -> pd.DataFrame:
    """Attach all supported indicators to the DataFrame in-place.

    Args:
        df: OHLCV DataFrame with columns: timestamp, open, high, low, close, volume.

    Returns:
        The same DataFrame with indicator columns appended.

    Notes:
        - Column names are dynamically generated by pandas_ta and may include
          parameter suffixes (e.g. "MACD_12_26_9", "RSI_14").
          Use ``utils._col()`` to look them up safely.
        - Indicators append: RSI_14, MACD_*, BB_*, EMA_7/25/99, ATRr_14, STOCHk_*, STOCHd_*
    """
    df.ta.rsi(length=14, append=True)
    df.ta.macd(fast=12, slow=26, signal=9, append=True)
    df.ta.bbands(length=20, std=2, append=True)
    for ema_len in [7, 25, 99]:
        df.ta.ema(length=ema_len, append=True)
    df.ta.atr(length=14, append=True)
    df.ta.stoch(append=True)
    return df


